//定义函数：f(x) = 4x⁴ + 25x³ + 2x² + 8x + 1.

import java.util.Scanner;
public class BisectionMethod {
    public static void main(String[] args) {
        double Eps, a, b;
        Scanner S = new Scanner(System.in);    //为输入左、右端点和精确度用
        System.out.print("二分法求函数零点\n" + "请输入初始区间左端点：");
        a = S.nextDouble();
        System.out.print("请输入初始区间右端点：");
        b = S.nextDouble();
        System.out.print("请输入精确度ε：");
        Eps = S.nextDouble();
        double c = (a + b) / 2;
        double A = 4 * Math.pow(a, 4) + 25 * Math.pow(a, 3) + 2 * Math.pow(a, 2) + 8 * a + 1;    
        double C = 4 * Math.pow(c, 4) + 25 * Math.pow(c, 3) + 2 * Math.pow(c, 2) + 8 * c + 1;    //定义f(a)和f(c)
        /*
         * 以上两行并没有声明新的函数, 而是声明了两个新的变量. 
         * 这样的话, A 和 B 的值, 只有使用 A = ... 或 B = ... 这样的赋值语句才能改变, 而不会随着 a 和 b 的值的改变而自动改变.
         * 所以, 后面的代码中, 每次取的 A 和 B 的值都是一样的, 尽管 a 和 b 在改变.
         * 声明一个函数 (在 Java 中称为 "方法") 的正确写法, 见修改版的 L6 - L8.
         * 后面的注释中, 都假定代码经过修改, 正确地声明了函数 f().
         */
        while (Math.abs(a - b) >= Eps) {
            if ((A * C) < 0) { // 如前所述, 上一行的 A 和 C 应该分别改成 f(a) 和 f(c).
                c = (a + b) / 2; // 这一行应该移在 if 前面
                b = c;
            } else {
                C = 0; // 这一行意义不明?
                // 根据原本的程序框图, 下面一整段 if (...) { ... } else { ... } 都应该移到这里面来的.
            }
            if (C == 0) {
                /*
                 * 这里的 C 也应该改成 f(c).
                 * 此外, 可以发现, f(c) 在这个程序中执行了两次.
                 * 为了避免程序不必要的重复计算, 可以将 f(c) 的结果赋给一个变量, 之后调用该变量即可.
                 * 如修改版中, 在 L21, f(c) 的值赋给了临时变量 f_c, 之后在 L22 和 L25 中 f_c 被重复使用.
                 */
                a = c; // 这一行和下面的 else 后面的 a = c 是一样的, 所以没必要两个分支里都写一遍, 在 if 前面写一遍即可.
                System.out.println("f(x)的零点精确到ε=" + Eps + "时的近似值为x₀=" + a); // 这一行不用了, 因为跳出循环后已经有一个输出语句了
                break;
            } else {
                a = c; // 如上所述, 这一行移除.
                continue; // 这一行不用了, 因为这里已经是 while 循环的最末尾. (还是说你误解了 continue 的意思?)
            }
        }
        if (Math.abs(a - b) < Eps) { // 这里不用再判断了, 因为精度达到要求 (或者刚好命中) 才能跳出 while 循环.
            System.out.println("f(x)的零点精确到ε=" + Eps + "时的近似值为x₀=" + a);
        }
        S.close();
        /*
         * 总结:
         * 除了对一些编程概念理解不充分以外, 这段代码的主要问题, 还在于对原书中程序框图没有透彻理解. 原程序框图的基本逻辑就是, 
         * 先取 a 和 b 的一个中间值 c; 如果已经达到精度要求或者零点刚好是 c, 那就直接结束; 否则, 如果零点在 c 左边, 那就将搜索范围缩小到左半边, 否则就缩小到右半边; 接着重复这个流程.
         * 换句话说就是, 如果 | a - b | < ε 或 f(c) = 0, 那就直接结束; 否则, 如果 f(a) * f(c) < 0, 那就令 b = c, 否则令 a = c; 接着重复这个流程.
         * 基于这样的理解, 本程序的核心算法, 就可以从上面几十行的代码, 优化成修改版中的仅五行代码.
         * 
         * 此外, 从上面的代码中可以看出, 你的编码风格 (缩进, 空格等) 是比较规范的, 已经超过了大部分编程初学者. 不过还有一些需要注意的地方.
         * 首先, 变量名不应该以大写字母开头, 这一条是大部分编程语言都适用的. 其次, 关于 if-else 语句的写法, 虽然像
         *    if (...) {
         *       ...
         *    } else {
         *       ...
         *    }
         * 这样写法偶尔会见到, 但标准的写法应该是
         *    if (...) {
         *       ...
         *    }
         *    else {
         *       ...
         *    }
         * 如果大括号内只有一条语句, 也习惯不写大括号. 如修改版中的 L22 - L23.
         */
    }
}
